test('new atlas creates all scales, edits and links places, undoes drawing, exports and reloads', async ({ page }) => {
  await seedCleanStorage(page)
  await page.goto('/')
  await dismissLaunchPrompts(page)
  await createProject(page, { title: 'Atlas Rebuild QA' })
  await page.getByRole('button', { name: 'Open Atlas', exact: true }).first().click()
  await page.getByRole('button', { name: 'Map', exact: true }).first().click()
  await expect(page.getByRole('heading', { name: 'Every story has a place.' })).toBeVisible()
  for (const scale of ['World','Region','Local','Interior']) {
    await page.getByRole('button', { name: '+ New map', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('Map name').fill(`${scale} QA`)
    await dialog.getByRole('button', { name: scale, exact: true }).click()
    await dialog.getByRole('button', { name: 'Create map →' }).click()
    await expect(page.getByLabel('Map name', { exact: true })).toHaveValue(`${scale} QA`)
    await expect(page.locator('.atlas-paper [data-object-id]')).not.toHaveCount(0)
    if (scale !== 'Interior') await page.getByRole('button', { name: '← Atlas', exact: true }).click()
  }
  // Grid visibility does not silently quantize placed furniture.
  await expect(page.getByLabel('Snap to grid', { exact: true })).not.toBeChecked()
  await page.getByRole('button', { name: 'Symbols', exact: true }).click()
  const interiorCanvas = page.locator('.atlas-paper > svg')
  const interiorBox = await interiorCanvas.boundingBox()
  await interiorCanvas.click({ position: { x: interiorBox.width*.413, y: interiorBox.height*.527 } })
  let furniture = (await readStorage(page, 'nf_maps')).find(m => m.mapType === 'interior').mapObjects.at(-1)
  expect(furniture.x).toBeCloseTo(1200*.413, 0)
  expect(furniture.y).toBeCloseTo(800*.527, 0)
  await page.getByLabel('Snap to grid', { exact: true }).check()
  await interiorCanvas.click({ position: { x: interiorBox.width*.413, y: interiorBox.height*.527 } })
  furniture = (await readStorage(page, 'nf_maps')).find(m => m.mapType === 'interior').mapObjects.at(-1)
  expect(furniture.x).toBe(480)
  expect(furniture.y).toBe(440)
  await page.getByLabel('Snap to grid', { exact: true }).uncheck()
  // A placed pin links to a new Location and is editable independently.
  await page.getByRole('button', { name: 'Place', exact: true }).click()
  const canvas = page.locator('.atlas-paper svg').first()
  const box = await canvas.boundingBox()
  await canvas.click({ position: { x: box.width*.45, y: box.height*.62 } })
  await page.getByLabel('Element name').fill('Secret chamber')
  await page.getByRole('button', { name: 'Create Location from this' }).click()
  await expect(page.getByRole('button', { name: 'Open location ↗' })).toBeVisible()
  const before = await page.locator('.atlas-paper [data-object-id]').count()
  // Drag a room, then undo/redo the complete gesture.
  await page.getByRole('button', { name: 'Room', exact: true }).click()
  await page.mouse.move(box.x+box.width*.1, box.y+box.height*.6)
  await page.mouse.down()
  await page.mouse.move(box.x+box.width*.25, box.y+box.height*.8, { steps: 8 })
  await page.mouse.up()
  await expect(page.locator('.atlas-paper [data-object-id]')).toHaveCount(before+1)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.locator('.atlas-paper [data-object-id]')).toHaveCount(before)
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await expect(page.locator('.atlas-paper [data-object-id]')).toHaveCount(before+1)
  await page.locator('.atlas-export summary').click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'PNG image', exact: true }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toBe('Interior QA.png')
  expect(await download.failure()).toBeNull()
  await page.evaluate(() => window.__yowStorageBridge?.flush())
  await page.reload()
  await waitForStorageHydration(page)
  await expect(page.getByLabel('Map name', { exact: true })).toHaveValue('Interior QA')
  const maps = await readStorage(page, 'nf_maps')
  expect(maps).toHaveLength(4)
  const interior = maps.find(m => m.mapType === 'interior')
  const place = interior.mapObjects.find(o => o.properties?.name === 'Secret chamber')
  const locations = await readStorage(page, 'nf_locations')
  expect(place.linkedEntity.entityId).toBe(locations.find(l => l.name === 'Secret chamber').id)
  await page.setViewportSize({ width: 1024, height: 768 })
  await expect(page.getByRole('button', { name: 'Fit', exact: true })).toBeVisible()
  const fit = await page.getByRole('button', { name: 'Fit', exact: true }).boundingBox()
  expect(fit.y+fit.height).toBeLessThan(715)
  await page.screenshot({ path: '/private/tmp/yow-atlas-editor.png', fullPage: true })
  await page.locator('.atlas-export summary').click()
  const jsonDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Editable map JSON' }).click()
  const exported = await jsonDownload
  const json = await readFile(await exported.path(), 'utf8')
  expect(JSON.parse(json).mapObjects.find(o => o.properties?.name === 'Secret chamber').linkedEntity).toEqual(place.linkedEntity)
  await page.getByRole('button', { name: '← Atlas', exact: true }).click()
  await page.locator('.atlas > input[type=file]').setInputFiles({ name: 'round-trip.json', mimeType: 'application/json', buffer: Buffer.from(json) })
  await expect(page.getByLabel('Map name', { exact: true })).toHaveValue('Interior QA')
  const afterImport = await readStorage(page, 'nf_maps')
  expect(afterImport).toHaveLength(5)
  expect(afterImport.at(-1).mapObjects.find(o => o.properties?.name === 'Secret chamber').linkedEntity).toEqual(place.linkedEntity)
  expect(afterImport.find(m => m.id === interior.id)).toEqual(interior)
  await page.getByRole('button', { name: '← Atlas', exact: true }).click()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('button', { name: /World QA/ }).click()
  await page.screenshot({ path: '/private/tmp/yow-atlas-world.png', fullPage: true })
})

test('existing maps retain their original editor and data when a new blank map is created', async ({ page }) => {
  await seedCleanStorage(page)
  await page.goto('/')
  await dismissLaunchPrompts(page)
  await createProject(page, { title: 'Original map safety QA' })
  const novels = await readStorage(page, 'nf_novels')
  const legacy = { id: 'legacy-map', novelId: novels[0].id, name: 'Original coast', mapType: 'world', mapObjects: [{ id: 'old-label', type: 'label', x: 400, y: 400, properties: { name: 'Preserve this', fontSize: 24 } }], metadata: { stylePreset: 'parchment' }, mapLayers: [] }
  await page.evaluate(async map => {
    window.__yowStorageBridge.setItem('nf_maps', JSON.stringify([map]))
    await window.__yowStorageBridge.flush()
  }, legacy)
  await page.reload()
  await waitForStorageHydration(page)
  await page.getByRole('navigation', { name: 'Workspace', exact: true }).getByRole('button', { name: 'Open Atlas', exact: true }).click()
  await page.getByRole('button', { name: 'Map', exact: true }).click()
  await expect(page.getByText('This map uses the original editor.')).toBeVisible()
  await page.getByRole('button', { name: 'Try the new builder' }).click()
  await page.getByRole('dialog').getByLabel('Map name').fill('A fresh start')
  await page.getByRole('button', { name: /Blank canvas/ }).click()
  await page.getByRole('button', { name: 'Create map →' }).click()
  await expect(page.locator('.atlas-paper [data-object-id]')).toHaveCount(0)
  expect((await readStorage(page, 'nf_maps')).find(m => m.id === legacy.id)).toEqual(legacy)
  await page.getByRole('button', { name: 'Land', exact: true }).click()
  await page.getByRole('group', { name:'Land drawing mode' }).getByRole('button', { name:'Freehand' }).click()
  const canvas = page.locator('.atlas-paper svg').first()
  const box = await canvas.boundingBox()
  await page.mouse.move(box.x+box.width*.3, box.y+box.height*.3)
  await page.mouse.down()
  for (const [x,y] of [[.6,.3],[.7,.5],[.55,.7],[.3,.6],[.3,.3]]) await page.mouse.move(box.x+box.width*x,box.y+box.height*y,{ steps: 6 })
  await page.mouse.up()
  await expect(page.locator('.atlas-paper [data-object-id]')).toHaveCount(1)
  await page.getByRole('button', { name: 'Select', exact: true }).click()
  await canvas.click({ position: { x: box.width*.5,y: box.height*.5 } })
  await expect(page.getByLabel('Element name')).toBeVisible()
  await canvas.focus()
  await page.keyboard.press('Delete')
  await expect(page.locator('.atlas-paper [data-object-id]')).toHaveCount(0)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.locator('.atlas-paper [data-object-id]')).toHaveCount(1)
})

test('cursor placement stays aligned through zoom, pan and expanded view; borders toggle without changing geometry', async ({ page }) => {
  await seedCleanStorage(page)
  await page.goto('/')
  await dismissLaunchPrompts(page)
  await createProject(page, { title: 'Pointer alignment QA' })
  await page.getByRole('navigation', { name: 'Workspace', exact: true }).getByRole('button', { name: 'Open Atlas', exact: true }).click()
  await page.getByRole('button', { name: 'Map', exact: true }).click()
  await page.getByRole('button', { name: '+ New map', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Map name').fill('Alignment')
  await page.getByRole('button', { name: 'Create map →' }).click()
  const header = await page.locator('.atlas-topbar').boundingBox()
  expect(header.height).toBeLessThanOrEqual(46)
  const canvas = page.locator('.atlas-paper > svg')
  const originalPaper = await canvas.boundingBox()
  const border = page.locator('.atlas-paper [data-object-id]').first().locator('path').first()
  const organicPath = await border.getAttribute('d')
  const original = (await readStorage(page, 'nf_maps'))[0].mapObjects
  await page.getByLabel('Organic borders', { exact: true }).uncheck()
  expect(await border.getAttribute('d')).not.toContain('Q')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  expect(await border.getAttribute('d')).toBe(organicPath)
  await page.getByLabel('Organic borders', { exact: true }).uncheck()
  expect((await readStorage(page, 'nf_maps'))[0].mapObjects).toEqual(original)
  await page.getByRole('button', { name: 'Expand canvas', exact: true }).click()
  await page.getByRole('button', { name: 'Hide panel', exact: true }).click()
  const expandedPaper = await canvas.boundingBox()
  expect(expandedPaper.width*expandedPaper.height).toBeGreaterThan(originalPaper.width*originalPaper.height*1.2)

  for (const zoom of [1, 1.25]) {
    await page.locator('.atlas-editor').evaluate((el,z) => { el.style.zoom=z }, zoom)
    await page.getByRole('button', { name: 'Zoom in', exact: true }).click()
    await page.getByRole('button', { name: 'Move view', exact: true }).click()
    await page.mouse.move(500,350)
    await page.mouse.down()
    await page.mouse.move(530,370)
    await page.mouse.up()
    await page.getByRole('button', { name: 'Place', exact: true }).click()
    const box = await canvas.boundingBox()
    const x = Math.max(150, box.x+box.width*.48), y = Math.max(200,box.y+box.height*.48)
    await page.mouse.click(x,y)
    const pin = page.locator('.atlas-paper [data-object-id]').last().locator('[data-location-dot]')
    const placed = await pin.boundingBox()
    expect(Math.abs(placed.x+placed.width/2-x)).toBeLessThan(2)
    expect(Math.abs(placed.y+placed.height/2-y)).toBeLessThan(2)
    // A closed inspector must not reopen and move the paper under the pointer.
    await expect(page.getByRole('button', { name: 'Show panel', exact: true })).toBeVisible()
  }
  await page.locator('.atlas-editor').evaluate(el => { el.style.zoom=1 })
  await page.getByRole('button', { name: 'Fit', exact: true }).click()
  await page.screenshot({ path: '/private/tmp/yow-atlas-expanded.png', fullPage: true })
  await page.getByRole('button', { name: 'Exit expanded view', exact: true }).click()
  await page.evaluate(() => window.__yowStorageBridge.flush())
  await page.reload()
  await waitForStorageHydration(page)
  await expect(page.getByLabel('Organic borders', { exact: true })).not.toBeChecked()
})

